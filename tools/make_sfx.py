"""Starbloom's sounds, gathered for the ROM.

  python3 tools/make_sfx.py --import   convert the chosen files from ../third_party/sfx (CC0 packs)
                                       into sfx/<name>.raw (8-bit, mono, 13379 Hz); kept in the repo
  python3 tools/make_sfx.py            write src/audio.s and src/audio.h (run by build.sh)

The firework sounds and the music are not here: tools/synth.c renders them into build/audio.
Credits are in sfx/CREDITS.md.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKS = os.path.join(ROOT, "..", "third_party", "sfx")
SFX_DIR = os.path.join(ROOT, "sfx")
RATE = 13379
UI = "kenney_interface/files/Audio/"
RPG = "kenney_rpg/files/Audio/"

# name: (source file under third_party/sfx, longest length in seconds, volume 0..1)
IMPORTS = {
    "move":    (UI + "tick_002.ogg", 0.10, 0.45),
    "select":  (UI + "select_002.ogg", 0.25, 0.6),
    "back":    (UI + "back_002.ogg", 0.25, 0.55),
    "nope":    (UI + "error_006.ogg", 0.30, 0.5),
    "coins":   (RPG + "handleCoins.ogg", 0.55, 0.8),
    "chop":    (RPG + "chop.ogg", 0.35, 0.9),
    "clink":   (RPG + "metalPot2.ogg", 0.30, 0.6),
    "crack":   (UI + "glass_002.ogg", 0.45, 0.8),
    "pickup":  ("frogpog/pick_up.wav", 0.30, 0.6),
    "page":    (RPG + "bookFlip1.ogg", 0.30, 0.7),
    "door":    (RPG + "doorOpen_1.ogg", 0.60, 0.6),
    "levelup": ("frogpog/level_up.wav", 1.00, 0.6),
    "cloth":   (RPG + "cloth1.ogg", 0.35, 0.7),
}
# Rendered by tools/synth.c into build/audio at 13379 Hz.
SYNTH = ["launch", "boom_s", "boom_m", "boom_l", "crackle", "glitter", "pop", "chime", "splash", "crafted"]
SFX = SYNTH + list(IMPORTS)
# Rendered by synth.c from tools/make_music.py at 18157 Hz. They all loop.
SONGS = ["title", "day", "forest", "beach", "quarry", "mine", "shop", "show", "review"]


def convert(name, src, max_len, gain):
    """Decode with ffmpeg, trim the silence at the start, cut to max_len with a short fade,
    normalize, and write signed 8-bit samples."""
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", os.path.join(PACKS, src), "-ac", "1", "-ar", str(RATE),
                          "-f", "s16le", "-"], capture_output=True, check=True).stdout
    s = [int.from_bytes(pcm[i:i + 2], "little", signed=True) for i in range(0, len(pcm) - 1, 2)]
    start = next((i for i, v in enumerate(s) if abs(v) > 600), 0)
    s = s[start:start + int(max_len * RATE)]
    peak = max(1, max(abs(v) for v in s))
    fade = int(0.03 * RATE)
    out = bytearray()
    for i, v in enumerate(s):
        f = min(1.0, (len(s) - i) / fade)
        out.append(max(-127, min(127, int(v / peak * 120 * gain * f))) & 0xFF)
    with open(os.path.join(SFX_DIR, name + ".raw"), "wb") as fh:
        fh.write(out)
    print(f"{name}: {len(out) / RATE:.2f} s from {src.split('/')[-1]}")


def write_tables():
    """audio.s pulls each sound into the ROM with .incbin, followed by silence (the DMA reads
    a little past the end); audio.h names them."""
    s = ["@ Generated by tools/make_sfx.py. Do not edit by hand.", "    .section .rodata", "    .align 2"]
    def blob(label, path):
        s.extend([f"{label}:", f'    .incbin "{path}"', f"{label}_end:", "    .space 320", "    .align 2"])
    for n in SYNTH:
        blob(f"sfx_{n}", f"build/audio/{n}.raw")
    for n in IMPORTS:
        blob(f"sfx_{n}", f"sfx/{n}.raw")
    for n in SONGS:
        blob(f"song_{n}", f"build/audio/{n}.raw")
    s += ["    .global sfx_table", "sfx_table:"] + [f"    .word sfx_{n}, sfx_{n}_end - sfx_{n}" for n in SFX]
    s += ["    .global song_table", "song_table:"] + [f"    .word song_{n}, song_{n}_end - song_{n}" for n in SONGS]
    with open(os.path.join(ROOT, "src", "audio.s"), "w") as f:
        f.write("\n".join(s) + "\n")
    h = ["// Generated by tools/make_sfx.py. Do not edit by hand.", "#pragma once", ""]
    h += [f"#define SFX_{n.upper()} {i}" for i, n in enumerate(SFX)] + [f"#define NUM_SFX {len(SFX)}", ""]
    h += [f"#define SONG_{n.upper()} {i}" for i, n in enumerate(SONGS)] + [f"#define NUM_SONGS {len(SONGS)}"]
    with open(os.path.join(ROOT, "src", "audio.h"), "w") as f:
        f.write("\n".join(h) + "\n")


if __name__ == "__main__":
    os.makedirs(SFX_DIR, exist_ok=True)
    if "--import" in sys.argv:
        for name, args in IMPORTS.items():
            convert(name, *args)
    write_tables()
