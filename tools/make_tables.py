"""Write src/tables.h: sine, sphere-radius, and heart-shape tables (8.8 fixed point)."""
import math, os

out = os.path.join(os.path.dirname(__file__), "..", "src", "tables.h")
lines = ["// Generated by tools/make_tables.py. Do not edit.", "#pragma once", ""]

sin = [round(math.sin(i * 2 * math.pi / 256) * 256) for i in range(256)]
lines.append("static const s16 sin_tab[256] = {" + ",".join(map(str, sin)) + "};")

# sqrt(1 - z^2) for z = 0..256 / 256: the radius of a sphere slice, so bursts look round in 3D.
rad = [round(math.sqrt(max(0.0, 1 - (z / 256) ** 2)) * 256) for z in range(257)]
lines.append("static const s16 sqrt_tab[257] = {" + ",".join(map(str, rad)) + "};")

heart = []
for i in range(48):
    t = i * 2 * math.pi / 48
    x = 16 * math.sin(t) ** 3
    y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
    heart += [round(x / 17 * 256), round(-y / 17 * 256)]   # screen y points down
lines.append("static const s16 heart_tab[96] = {" + ",".join(map(str, heart)) + "};")

open(out, "w").write("\n".join(lines) + "\n")
